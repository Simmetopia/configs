-- Compact tool progress without processes/providers.
vim.opt.rtp:append(vim.fn.getcwd())
local tools = require('ai.ui.tools')
local session = {}
local a = tools.start(session, { toolName = 'bash', toolCallId = 'a', args = { command = 'rg -n TODO\n lua' } })
assert(a.name == 'bash' and a.detail == 'rg -n TODO lua' and a.state == 'running', vim.inspect(a))
local b = tools.start(session, { toolName = 'bash', toolCallId = 'b', args = { command = 'npm test' } })
assert(b.detail == 'npm test')
local fa = tools.finish(session, { toolName = 'bash', toolCallId = 'a' })
assert(rawequal(fa, a))
assert(fa.state == 'done' and type(fa.elapsed) == 'number', vim.inspect(fa))
local fb = tools.finish(session, { toolName = 'bash', toolCallId = 'b', isError = true })
assert(fb.state == 'failed', vim.inspect(fb))
assert(next(session.tools) == nil)
assert(tools.start(session, { toolName = 'read', args = { path = 'lua/init.lua', offset = 20 } }).detail
  == 'lua/init.lua (line 20)')
assert(tools.start(session, { toolName = 'grep', args = { pattern = 'TODO', path = 'lua' } }).detail == 'TODO in lua')
local ws = tools.start(session, { toolName = 'web_search', args = { query = 'Neovim RPC' } })
assert(ws.name == 'web_search' and ws.detail == 'Neovim RPC')
local orphan = tools.finish({}, { toolName = 'edit' })
assert(orphan.state == 'done' and orphan.elapsed == nil, vim.inspect(orphan))
local edit = tools.start(session, { toolName = 'edit', args = { path = 'a.lua', oldText = 'SECRET', newText = 'SECRET' } })
assert(not vim.inspect(edit):find('SECRET', 1, true))
local long = tools.start(session, { toolName = 'bash', args = { command = string.rep('界', 200) } })
assert(vim.fn.strchars(long.detail) < 145)
assert(long.detail:find('…', 1, true))
assert(pcall(tools.start, session, { toolName = 'custom', args = vim.NIL }))
print('AI tool progress tests passed')
